import { existsSync } from 'node:fs';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import type { ResolvedConfig } from '../config.js';
import type { RNProject } from '../project.js';
import { workspaceDir } from '../project.js';
import { writeEmptyAppProject } from './xcodeproj.js';

export const PREBUILD_TARGET = 'NativepiecePrebuild';
export const PODS_SCHEME = `Pods-${PREBUILD_TARGET}`;

export interface IOSWorkspace {
  dir: string;
  podfile: string;
  xcworkspace: string;
}

function rubyString(value: string): string {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

// RN CLI의 autolinking 설정을 출력하는 스크립트다. RN은 Pod 경로를 project.ios.sourceDir 기준
// 상대 경로로 계산하므로, sourceDir을 이 작업 공간으로 바꿔서 출력한다. ios/ 폴더가 없는 모듈 프로젝트도 동작한다.
function renderAutolinkScript(project: RNProject, workspaceDir: string): string {
  return `// Generated by Nativepiece. Do not edit.
const { execFileSync } = require('node:child_process');

const json = execFileSync(process.execPath, [${JSON.stringify(path.join(project.reactNativePath, 'cli.js'))}, 'config'], {
  cwd: ${JSON.stringify(project.root)},
  encoding: 'utf8',
  maxBuffer: 64 * 1024 * 1024,
});
const config = JSON.parse(json);
config.project = config.project ?? {};
config.project.ios = { ...(config.project.ios ?? {}), sourceDir: ${JSON.stringify(workspaceDir)} };
process.stdout.write(JSON.stringify(config));
`;
}

// 모듈 프로젝트의 package.json을 기준으로 autolinking하는 Podfile을 만든다.
// PopPang처럼 상위 디렉터리를 RN 루트로 가정하지 않고 절대 경로를 쓴다.
function renderPodfile(config: ResolvedConfig, project: RNProject, autolinkScript: string): string {
  return `# Generated by Nativepiece. Do not edit.
source 'https://cdn.cocoapods.org/'
platform :ios, ${rubyString(config.ios.deploymentTarget)}

require File.join(${rubyString(project.reactNativePath)}, 'scripts', 'react_native_pods')

inhibit_all_warnings!

prepare_react_native_project!

autolink_command = ['node', ${rubyString(autolinkScript)}]

target ${rubyString(PREBUILD_TARGET)} do
  use_frameworks! :linkage => :static

  config = use_native_modules!(autolink_command)

  use_react_native!(
    :path => config[:reactNativePath],
    :app_path => ${rubyString(project.root)}
  )

  post_install do |installer|
    react_native_post_install(
      installer,
      config[:reactNativePath],
      :mac_catalyst_enabled => false
    )
  end
end
`;
}

export async function prepareIOSWorkspace(config: ResolvedConfig, project: RNProject): Promise<IOSWorkspace> {
  const dir = workspaceDir(project.root, 'ios');
  await mkdir(dir, { recursive: true });

  const autolinkScript = path.join(dir, 'autolink-config.cjs');
  await writeFile(autolinkScript, renderAutolinkScript(project, dir));

  const podfile = path.join(dir, 'Podfile');
  await writeFile(podfile, renderPodfile(config, project, autolinkScript));

  // Xcode 빌드 단계의 RN 스크립트가 머신마다 다른 node 경로를 쓰지 않도록 PATH에서 찾게 한다.
  await writeFile(path.join(dir, '.xcode.env'), 'export NODE_BINARY=$(command -v node)\n');

  const xcodeproj = path.join(dir, `${PREBUILD_TARGET}.xcodeproj`);
  if (!existsSync(xcodeproj)) {
    await writeEmptyAppProject(xcodeproj, PREBUILD_TARGET, config.ios.deploymentTarget);
  }

  return { dir, podfile, xcworkspace: path.join(dir, `${PREBUILD_TARGET}.xcworkspace`) };
}
