import { cp, mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import type { ResolvedConfig } from '../config.js';
import { packagePath } from '../utils/assets.js';
import { run } from '../utils/exec.js';
import type { BundleOutput } from '../commands/bundle.js';
import type { FrameworksOutput } from './frameworks.js';
import type { LinkerFlags } from './linker-flags.js';
import { renderForceLoadSource } from './prelink.js';
import { devServerEntry, type GeneratedSources } from '../codegen/index.js';

const KIT_TARGET = 'NativepieceKit';
const BINARIES_TARGET = 'NativepieceBinaries';

function swiftPlatform(deploymentTarget: string): string {
  const [major, minor = '0'] = deploymentTarget.split('.');
  return minor === '0' ? `.iOS(.v${major})` : `.iOS("${deploymentTarget}")`;
}

// unsafeFlags는 원격 패키지에서 쓸 수 없어서 쓰지 않는다.
// -ObjC는 미리 합친 framework와 force_load.c로 대신하고(prelink.ts), weak framework는 일반 링크로 바꾼다.
// weak로 링크되던 JavaScriptCore는 모든 iOS 버전에 있다.
function renderLinkerSettings(flags: LinkerFlags): string {
  const lines: string[] = [];
  for (const library of flags.libraries) lines.push(`.linkedLibrary("${library}")`);
  for (const framework of [...flags.frameworks, ...flags.weakFrameworks].sort()) {
    lines.push(`.linkedFramework("${framework}", .when(platforms: [.iOS]))`);
  }
  return lines.map((line) => `                ${line},`).join('\n');
}

export interface PackageManifest {
  names: string[];
  linkerFlags: LinkerFlags;
}

export const PACKAGE_MANIFEST = '.nativepiece-package.json';

export type BinaryTargetSource = (name: string) => string;

// 로컬 패키지는 Frameworks/ 경로를, 원격 패키지(publish)는 url과 checksum을 쓴다.
const localBinary: BinaryTargetSource = (name) => `path: "Frameworks/${name}.xcframework"`;

// sourcesRoot는 Package.swift 기준 소스 폴더다. 같은 레포 배포에서는 RN 프로젝트 안의 폴더를 가리킨다.
export function renderPackageSwift(
  config: ResolvedConfig,
  frameworks: PackageManifest,
  binary: BinaryTargetSource = localBinary,
  sourcesRoot = 'Sources',
): string {
  const binaryDependencies = frameworks.names.map((name) => `                "${name}",`).join('\n');
  const binaryTargets = frameworks.names
    .map((name) => `        .binaryTarget(name: "${name}", ${binary(name)}),`)
    .join('\n');

  return `// swift-tools-version:5.9
// Generated by Nativepiece ${config.version}. Do not edit.
import PackageDescription

let package = Package(
    name: "${config.name}",
    platforms: [
        ${swiftPlatform(config.ios.deploymentTarget)}
    ],
    products: [
        .library(name: "${config.name}", targets: ["${config.name}"])
    ],
    targets: [
        .target(
            name: "${config.name}",
            dependencies: ["${KIT_TARGET}"],
            path: "${sourcesRoot}/${config.name}",
            resources: [.copy("ReactNative")]
        ),
        .target(
            name: "${KIT_TARGET}",
            dependencies: ["${BINARIES_TARGET}"],
            path: "${sourcesRoot}/${KIT_TARGET}"
        ),
        // React Native와 네이티브 모듈 XCFramework를 한 번에 링크하는 C 타깃이다.
        .target(
            name: "${BINARIES_TARGET}",
            dependencies: [
${binaryDependencies}
            ],
            path: "${sourcesRoot}/${BINARIES_TARGET}",
            linkerSettings: [
${renderLinkerSettings(frameworks.linkerFlags)}
            ]
        ),
${binaryTargets}
    ]
)
`;
}

function renderModuleSource(config: ResolvedConfig): string {
  const devEntry = devServerEntry(config);
  return `// Generated by Nativepiece ${config.version}. Do not edit.
import Foundation
@_exported import ${KIT_TARGET}

public enum ${config.name} {
    public static let version = "${config.version}"

    /// 런타임을 시작해요. 앱 시작 시점(AppDelegate 등)에 한 번 호출해요.
    ///
    /// \`devServer\`를 넘기면 Metro 개발 서버의 번들을 써요. \`nativepiece build ios --dev\`로 만든 개발용 패키지에서만 써요.
    /// 개발 서버에 연결할 수 없으면 앱에 들어 있는 번들로 돌아가요.
    @MainActor
    public static func start(prewarm: Bool = true, devServer: NativepieceDevServer? = nil) {
        Nativepiece.shared.configure(
            embeddedBundleURL: Bundle.module.url(forResource: "main", withExtension: "jsbundle", subdirectory: "ReactNative")
        )
        Nativepiece.shared.bundleURLOverride = devServer?.bundleURL(entry: "${devEntry}")
        Nativepiece.shared.start(prewarm: prewarm)
    }
}
`;
}

// XCFramework, 호스트 SDK 소스, JS 번들을 하나의 Swift Package로 묶는다.
export async function assembleSwiftPackage(
  config: ResolvedConfig,
  frameworks: FrameworksOutput,
  jsBundle: BundleOutput,
  generated: GeneratedSources,
  outDir: string,
): Promise<string> {
  await rm(outDir, { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });

  // APFS에서는 clone으로 복사돼서 수백 MB여도 빠르다.
  await run('cp', ['-c', '-R', frameworks.dir, path.join(outDir, 'Frameworks')]);

  const kitDir = path.join(outDir, 'Sources', KIT_TARGET);
  await mkdir(kitDir, { recursive: true });
  await cp(packagePath('assets', 'ios-host', 'Sources', KIT_TARGET), kitDir, { recursive: true });

  const binariesDir = path.join(outDir, 'Sources', BINARIES_TARGET);
  await mkdir(path.join(binariesDir, 'include'), { recursive: true });
  await writeFile(path.join(binariesDir, 'force_load.c'), renderForceLoadSource(frameworks.forceLoadSymbols));
  await writeFile(
    path.join(binariesDir, 'include', `${BINARIES_TARGET}.h`),
    '// Generated by Nativepiece. Do not edit.\n// 공개 API가 없는 링크 전용 타깃이에요.\n',
  );

  const moduleDir = path.join(outDir, 'Sources', config.name);
  const resourcesDir = path.join(moduleDir, 'ReactNative');
  await mkdir(resourcesDir, { recursive: true });
  await writeFile(path.join(moduleDir, `${config.name}.swift`), renderModuleSource(config));
  if (generated.swift) await writeFile(path.join(moduleDir, `${config.name}Contract.swift`), generated.swift);
  await cp(jsBundle.bundleFile, path.join(resourcesDir, 'main.jsbundle'));
  if ((await readdir(jsBundle.assetsDir)).length > 0) {
    await cp(jsBundle.assetsDir, path.join(resourcesDir, 'assets'), { recursive: true });
  }

  await writeFile(path.join(outDir, 'Package.swift'), renderPackageSwift(config, frameworks));
  // publish가 원격용 Package.swift를 다시 만들 수 있게 framework 목록을 남긴다.
  const manifest: PackageManifest = { names: frameworks.names, linkerFlags: frameworks.linkerFlags };
  await writeFile(path.join(outDir, PACKAGE_MANIFEST), `${JSON.stringify(manifest, null, 2)}\n`);
  return outDir;
}
