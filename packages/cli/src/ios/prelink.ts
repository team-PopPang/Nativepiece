import { existsSync } from 'node:fs';
import { mkdtemp, readdir, rename, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { run } from '../utils/exec.js';

// 정적 framework를 앱이 -ObjC 없이도 통째로 링크하게 만든다.
//
// RN 네이티브 모듈 클래스는 코드에서 직접 참조되지 않고 실행 중에 이름으로 찾기 때문에,
// 보통은 앱이 -ObjC로 링커에게 ObjC 코드를 모두 넣으라고 알려야 한다. 하지만 SwiftPM은 원격 패키지의
// unsafeFlags(-ObjC 포함)를 허용하지 않는다. 그래서 빌드할 때 framework의 모든 object를 하나로 미리 합치고
// (ld -r), 패키지의 C 타깃이 framework마다 심볼 하나를 참조하게 한다. 심볼 하나가 참조되면 링커는
// 그 심볼이 든 object 전체, 즉 framework 전체를 가져온다.

export interface ForceLoadSymbol {
  framework: string;
  symbol: string;
}

async function isStaticArchive(binary: string): Promise<boolean> {
  return (await run('file', ['-b', binary], { inherit: false })).includes('ar archive');
}

function platformName(sliceDirectory: string): string {
  return /-simulator$/.test(sliceDirectory) ? 'ios-simulator' : 'ios';
}

async function prelinkArchive(binary: string, platform: string, deploymentTarget: string, tempDir: string) {
  const archs = (await run('lipo', ['-archs', binary], { inherit: false })).trim().split(/\s+/);
  const thinLibraries: string[] = [];

  for (const arch of archs) {
    const thin = path.join(tempDir, `${arch}.a`);
    if (archs.length > 1) await run('lipo', ['-thin', arch, binary, '-output', thin], { inherit: false });
    const input = archs.length > 1 ? thin : binary;
    const merged = path.join(tempDir, `${arch}.o`);
    await run(
      'xcrun',
      ['ld', '-r', '-arch', arch, '-platform_version', platform, deploymentTarget, deploymentTarget, '-force_load', input, '-o', merged],
      { inherit: false },
    );
    const library = path.join(tempDir, `${arch}-merged.a`);
    await run('xcrun', ['libtool', '-static', '-o', library, merged], { inherit: false });
    thinLibraries.push(library);
  }

  const output = path.join(tempDir, 'output');
  if (thinLibraries.length > 1) {
    await run('lipo', ['-create', ...thinLibraries, '-output', output], { inherit: false });
  } else {
    await rename(thinLibraries[0], output);
  }
  await rename(output, binary);
}

// CocoaPods는 Pod마다 PodsDummy_<이름> 클래스를 넣는다. 없으면 weak가 아닌 아무 외부 심볼을 쓴다.
async function pickSymbol(binary: string): Promise<string | null> {
  const output = await run('nm', ['-gUm', binary], { inherit: false });
  const symbols = output
    .split('\n')
    .filter((line) => / external /.test(line) && !/weak|private/.test(line))
    .map((line) => line.trim().split(/\s+/).pop() ?? '')
    .filter(Boolean);
  return symbols.find((symbol) => symbol.startsWith('_OBJC_CLASS_$_PodsDummy_')) ?? symbols[0] ?? null;
}

export async function prelinkStaticFrameworks(frameworksDir: string, deploymentTarget: string): Promise<ForceLoadSymbol[]> {
  const symbols: ForceLoadSymbol[] = [];

  for (const xcframework of (await readdir(frameworksDir)).filter((entry) => entry.endsWith('.xcframework')).sort()) {
    const name = xcframework.replace(/\.xcframework$/, '');
    const xcframeworkPath = path.join(frameworksDir, xcframework);
    let symbol: string | null = null;
    let isStatic = false;

    for (const slice of await readdir(xcframeworkPath)) {
      const binary = path.join(xcframeworkPath, slice, `${name}.framework`, name);
      if (!existsSync(binary) || !(await isStaticArchive(binary))) continue;
      isStatic = true;

      const tempDir = await mkdtemp(path.join(os.tmpdir(), 'nativepiece-prelink-'));
      try {
        await prelinkArchive(binary, platformName(slice), deploymentTarget, tempDir);
      } finally {
        await rm(tempDir, { recursive: true, force: true });
      }

      const sliceSymbol = await pickSymbol(binary);
      if (!sliceSymbol) throw new Error(`${name} (${slice})에서 참조할 심볼을 찾지 못했어요.`);
      if (symbol && symbol !== sliceSymbol) {
        throw new Error(`${name}의 slice마다 고른 심볼이 달라요: ${symbol}, ${sliceSymbol}`);
      }
      symbol = sliceSymbol;
    }

    if (isStatic && symbol) symbols.push({ framework: name, symbol });
  }

  return symbols;
}

export function renderForceLoadSource(symbols: ForceLoadSymbol[]): string {
  const declarations = symbols.map(
    ({ framework, symbol }, index) => `extern char np_force_load_${index} __asm("${symbol}"); // ${framework}`,
  );
  const references = symbols.map((_, index) => `    &np_force_load_${index},`);
  return `// Generated by Nativepiece. Do not edit.
//
// 정적 framework마다 심볼 하나를 참조해서 링커가 framework 전체를 앱에 넣게 해요.
// 원격 Swift Package에서는 -ObjC 같은 unsafeFlags를 쓸 수 없어서 이 방식으로 대신해요.

${declarations.join('\n')}

__attribute__((used)) static const void *const np_force_load[] = {
${references.join('\n')}
};
`;
}
