import { existsSync, readFileSync } from 'node:fs';
import { appendFile, cp, mkdir, mkdtemp, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import type { ResolvedConfig } from '../config.js';
import type { RNProject } from '../project.js';
import { workspaceDir } from '../project.js';
import { PACKAGE_MANIFEST, renderPackageSwift, type PackageManifest } from '../ios/package.js';
import { run } from '../utils/exec.js';
import { log } from '../utils/log.js';

export interface PublishIOSOptions {
  repo?: string;
  dryRun?: boolean;
}

interface BinaryAsset {
  name: string;
  file: string;
  checksum: string;
}

function assetName(framework: string): string {
  return `${framework}.xcframework.zip`;
}

// SwiftPM binaryTarget은 xcframework가 루트에 든 zip과 그 checksum을 요구한다.
async function zipFrameworks(packageDir: string, names: string[], outDir: string): Promise<BinaryAsset[]> {
  const assets: BinaryAsset[] = [];
  for (const name of names) {
    const file = path.join(outDir, assetName(name));
    await run('ditto', ['-c', '-k', '--sequesterRsrc', '--keepParent', path.join(packageDir, 'Frameworks', `${name}.xcframework`), file]);
    // compute-checksum은 실행 위치에 .build/를 만들어서 레포 밖 작업 폴더에서 실행한다.
    const checksum = (await run('swift', ['package', 'compute-checksum', file], { cwd: outDir, inherit: false })).trim();
    assets.push({ name, file, checksum });
  }
  return assets;
}

const GENERATED_MARKER = 'Generated by Nativepiece';
const DEFAULT_PACKAGE_DIR = 'swift-package';

// 전용 레포는 레포 전체를 Swift Package로 채우고, 같은 레포는 Package.swift와 packageDir만 바꾼다.
type PublishTarget =
  | { mode: 'separate'; repo: string }
  | { mode: 'same'; repo: string; gitRoot: string; packageDir: string; sourcesRoot: string };

function renderReadme(config: ResolvedConfig, repo: string): string {
  return `<!-- ${GENERATED_MARKER}. Do not edit. -->
# ${config.name} (iOS)

[Nativepiece](https://github.com/team-PopPang/Nativepiece)로 만든 React Native 모듈의 Swift Package예요. 이 파일들은 \`nativepiece publish ios\`가 만들어요. 직접 고치지 마세요.

\`\`\`swift
.package(url: "https://github.com/${repo}", exact: "${config.version}")
\`\`\`

바이너리는 이 레포의 GitHub Release에 있어요. 레포가 비공개라면 Xcode가 바이너리를 받을 수 있게 \`~/.netrc\`에 읽기 권한 토큰을 넣어 주세요.

\`\`\`
machine api.github.com
  login x-access-token
  password <GitHub 토큰>
\`\`\`
`;
}

// rootDir에 배포할 파일을 쓴다. 전용 레포는 rootDir 전체, 같은 레포는 Package.swift와 sourcesRoot 폴더만 쓴다.
async function stagePackage(
  config: ResolvedConfig,
  packageDir: string,
  rootDir: string,
  target: PublishTarget,
  manifest: PackageManifest,
  binary: (name: string) => string,
) {
  const sourcesRoot = target.mode === 'same' ? target.sourcesRoot : 'Sources';
  const sourcesDir = path.join(rootDir, sourcesRoot);
  await rm(sourcesDir, { recursive: true, force: true });
  await mkdir(sourcesDir, { recursive: true });
  await writeFile(path.join(rootDir, 'Package.swift'), renderPackageSwift(config, manifest, binary, sourcesRoot));
  await cp(path.join(packageDir, 'Sources'), sourcesDir, { recursive: true });

  if (target.mode === 'separate') {
    await writeFile(path.join(rootDir, 'README.md'), renderReadme(config, target.repo));
    await writeFile(path.join(rootDir, '.gitignore'), '.build/\n.swiftpm/\n');
    return;
  }
  // 같은 레포에서는 루트 README를 건드리지 않고 사용법을 packageDir에 둔다.
  await writeFile(path.join(sourcesDir, 'README.md'), renderReadme(config, target.repo));
  const gitignorePath = path.join(rootDir, '.gitignore');
  const gitignore = existsSync(gitignorePath) ? await readFile(gitignorePath, 'utf8') : '';
  const lines = new Set(gitignore.split('\n').map((line) => line.trim()));
  const missing = ['.build/', '.swiftpm/'].filter((entry) => !lines.has(entry));
  if (missing.length > 0) {
    const prefix = gitignore && !gitignore.endsWith('\n') ? '\n' : '';
    await appendFile(gitignorePath, `${prefix}\n# Swift Package (nativepiece publish ios)\n${missing.join('\n')}\n`);
  }
}

async function draftAssetIds(repo: string, version: string): Promise<Map<string, number>> {
  const json = await run('gh', ['api', `repos/${repo}/releases`, '--jq', `[.[] | select(.tag_name == "${version}" and .draft)][0].assets`], {
    inherit: false,
  });
  const assets = JSON.parse(json) as { id: number; name: string }[] | null;
  if (!assets?.length) throw new Error(`${repo}의 ${version} draft release에서 asset을 찾지 못했어요.`);
  return new Map(assets.map((asset) => [asset.name, asset.id]));
}

async function tagExists(repo: string, tag: string): Promise<boolean> {
  try {
    await run('gh', ['api', `repos/${repo}/git/ref/tags/${tag}`], { inherit: false });
    return true;
  } catch {
    return false;
  }
}

function git(cwd: string, ...args: string[]): Promise<string> {
  return run('git', ['-C', cwd, ...args], { inherit: false }).then((output) => output.trim());
}

// https://github.com/owner/name(.git)와 git@github.com:owner/name(.git)를 owner/name으로 바꾼다.
function parseGitHubRepo(url: string): string | null {
  const match = url.trim().match(/github\.com[:/]([\w.-]+)\/([\w.-]+?)(?:\.git)?\/?$/);
  return match ? `${match[1]}/${match[2]}` : null;
}

async function originRepository(projectRoot: string): Promise<{ repo: string; gitRoot: string } | null> {
  try {
    const gitRoot = await git(projectRoot, 'rev-parse', '--show-toplevel');
    const repo = parseGitHubRepo(await git(projectRoot, 'remote', 'get-url', 'origin'));
    return repo ? { repo, gitRoot } : null;
  } catch {
    return null;
  }
}

async function resolveTarget(config: ResolvedConfig, project: RNProject, options: PublishIOSOptions): Promise<PublishTarget> {
  const repo = options.repo ?? config.publish?.ios?.repo;
  const origin = await originRepository(path.resolve(project.root));
  // 지정한 레포가 지금 레포와 같으면 같은 레포 모드로 배포한다. 전용 레포 모드는 레포 내용을 모두 지우기 때문이다.
  if (origin && (!repo || repo.toLowerCase() === origin.repo.toLowerCase())) {
    const packageDir = path.resolve(project.root, config.publish?.ios?.packageDir ?? DEFAULT_PACKAGE_DIR);
    const sourcesRoot = path.relative(origin.gitRoot, packageDir).split(path.sep).join('/');
    return { mode: 'same', repo: origin.repo, gitRoot: origin.gitRoot, packageDir, sourcesRoot };
  }
  if (!repo) {
    throw new Error(
      '배포할 레포를 찾지 못했어요. GitHub origin이 있는 git 레포에서 실행하거나, --repo owner/name 또는 publish.ios.repo를 넣어 주세요.',
    );
  }
  return { mode: 'separate', repo };
}

// Nativepiece가 만들지 않은 Package.swift나 폴더를 덮어쓰지 않는다.
async function assertGenerated(file: string, description: string) {
  if (!existsSync(file)) return;
  if (!(await readFile(file, 'utf8')).includes(GENERATED_MARKER)) {
    throw new Error(`${description}이(가) 이미 있는데 Nativepiece가 만든 파일이 아니에요. 덮어쓰지 않아요: ${file}`);
  }
}

async function checkSameRepository(target: Extract<PublishTarget, { mode: 'same' }>, dryRun: boolean) {
  if (path.relative(target.gitRoot, target.packageDir).startsWith('..')) {
    throw new Error(`publish.ios.packageDir는 git 레포 안에 있어야 해요: ${target.packageDir}`);
  }
  await assertGenerated(path.join(target.gitRoot, 'Package.swift'), '레포 루트의 Package.swift');
  if (existsSync(target.packageDir)) {
    await assertGenerated(path.join(target.packageDir, 'README.md'), `${target.sourcesRoot} 폴더`);
    if (!existsSync(path.join(target.packageDir, 'README.md'))) {
      throw new Error(`${target.sourcesRoot} 폴더가 이미 있는데 Nativepiece가 만든 폴더가 아니에요. publish.ios.packageDir를 바꿔 주세요.`);
    }
  }
  if (dryRun) return;

  if (await git(target.gitRoot, 'status', '--porcelain')) {
    throw new Error('커밋하지 않은 변경이 있어요. 배포 커밋에 섞이지 않게 먼저 커밋하거나 정리해 주세요.');
  }
  const defaultBranch = (
    await run('gh', ['repo', 'view', target.repo, '--json', 'defaultBranchRef', '--jq', '.defaultBranchRef.name'], { inherit: false })
  ).trim();
  const branch = await git(target.gitRoot, 'symbolic-ref', '--short', 'HEAD').catch(() => '(detached)');
  if (branch !== defaultBranch) {
    throw new Error(`배포는 기본 브랜치(${defaultBranch})에서 해요. 지금 브랜치: ${branch}`);
  }
  await git(target.gitRoot, 'fetch', '--quiet', 'origin', defaultBranch);
  if ((await git(target.gitRoot, 'rev-parse', 'HEAD')) !== (await git(target.gitRoot, 'rev-parse', `origin/${defaultBranch}`))) {
    throw new Error(`로컬 ${defaultBranch}가 origin/${defaultBranch}와 달라요. pull이나 push로 먼저 맞춰 주세요.`);
  }
}

// 전용 레포 모드는 레포 내용을 모두 바꾸므로 RN 프로젝트나 직접 만든 패키지 레포에는 배포하지 않는다.
async function checkSeparateRepository(repo: string) {
  const content = async (file: string) => {
    try {
      const encoded = await run('gh', ['api', `repos/${repo}/contents/${file}`, '--jq', '.content'], { inherit: false });
      return Buffer.from(encoded, 'base64').toString('utf8');
    } catch {
      return null;
    }
  };
  if ((await content('package.json')) !== null) {
    throw new Error(
      `${repo}에 package.json이 있어요. 전용 레포 모드는 레포 내용을 모두 바꿔서 이 레포에는 배포하지 않아요.\n` +
        '이 레포에 같이 배포하려면 그 레포를 clone한 RN 프로젝트에서 --repo 없이 실행해 주세요.',
    );
  }
  const packageSwift = await content('Package.swift');
  if (packageSwift !== null && !packageSwift.includes(GENERATED_MARKER)) {
    throw new Error(`${repo}의 Package.swift는 Nativepiece가 만든 파일이 아니에요. 덮어쓰지 않아요.`);
  }
}

// 배포 레포의 내용을 이번 버전의 Package.swift와 소스로 바꾸고, 버전 태그를 붙여 푸시한다.
async function pushPackageRepository(repo: string, version: string, stageDir: string) {
  const cloneDir = await mkdtemp(path.join(os.tmpdir(), 'nativepiece-publish-'));
  try {
    await run('gh', ['repo', 'clone', repo, cloneDir, '--', '--quiet'], { inherit: false });
    for (const entry of await readdir(cloneDir)) {
      if (entry !== '.git') await rm(path.join(cloneDir, entry), { recursive: true, force: true });
    }
    await cp(stageDir, cloneDir, { recursive: true });

    const branch = (await git(cloneDir, 'symbolic-ref', '--short', 'HEAD').catch(() => 'main')) || 'main';
    await git(cloneDir, 'add', '-A');
    await git(cloneDir, 'commit', '-m', `Release ${version}`);
    await git(cloneDir, 'tag', version);
    await git(cloneDir, 'push', 'origin', `HEAD:${branch}`);
    await git(cloneDir, 'push', 'origin', version);
  } finally {
    await rm(cloneDir, { recursive: true, force: true });
  }
}

// 지금 레포에 배포 파일만 커밋하고 태그를 붙여 푸시한다. 다른 파일은 사전 확인에서 깨끗한 상태임을 확인했다.
async function pushSameRepository(target: Extract<PublishTarget, { mode: 'same' }>, version: string) {
  const branch = await git(target.gitRoot, 'symbolic-ref', '--short', 'HEAD');
  await git(target.gitRoot, 'add', '-A', '--', 'Package.swift', '.gitignore', target.sourcesRoot);
  await git(target.gitRoot, 'commit', '-m', `Release ${version}`);
  await git(target.gitRoot, 'tag', version);
  await git(target.gitRoot, 'push', 'origin', `HEAD:${branch}`);
  await git(target.gitRoot, 'push', 'origin', version);
}

async function listFiles(dir: string, base = dir): Promise<string[]> {
  const files: string[] = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await listFiles(fullPath, base)));
    else files.push(path.relative(base, fullPath));
  }
  return files.sort();
}

export async function publishIOS(config: ResolvedConfig, project: RNProject, options: PublishIOSOptions): Promise<void> {
  const target = await resolveTarget(config, project, options);
  const { repo } = target;

  const packageDir = workspaceDir(project.root, 'output', 'ios', config.name);
  const manifestPath = path.join(packageDir, PACKAGE_MANIFEST);
  if (!existsSync(manifestPath)) {
    throw new Error(`배포할 Swift Package가 없어요. 먼저 \`nativepiece build ios\`를 실행해 주세요: ${packageDir}`);
  }
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8')) as PackageManifest;
  const version = config.version;

  if (target.mode === 'same') {
    log.info(`같은 레포에 배포해요: ${repo} (Package.swift, ${target.sourcesRoot}/)`);
    await checkSameRepository(target, options.dryRun ?? false);
  } else {
    log.info(`전용 레포에 배포해요: ${repo}`);
    await checkSeparateRepository(repo);
  }

  if (!options.dryRun && (await tagExists(repo, version))) {
    throw new Error(`${repo}에 ${version} 태그가 이미 있어요. 배포한 버전은 덮어쓰지 않아요. 버전을 올려 주세요.`);
  }

  const publishDir = workspaceDir(project.root, 'publish', 'ios', version);
  const assetsDir = path.join(publishDir, 'assets');
  const stageDir = path.join(publishDir, 'package');
  await rm(publishDir, { recursive: true, force: true });
  await mkdir(assetsDir, { recursive: true });
  await mkdir(stageDir, { recursive: true });

  log.step('XCFramework 압축과 checksum 계산');
  const assets = await zipFrameworks(packageDir, manifest.names, assetsDir);
  const byName = new Map(assets.map((asset) => [asset.name, asset]));

  if (options.dryRun) {
    await stagePackage(config, packageDir, stageDir, target, manifest, (name) => {
      const asset = byName.get(name)!;
      return `url: "https://github.com/${repo}/releases/download/${version}/${assetName(name)}", checksum: "${asset.checksum}"`;
    });
    log.success(`배포할 내용을 만들었어요 (dry run): ${publishDir}`);
    if (target.mode === 'same') {
      log.info('레포에서 바뀌는 파일 (.gitignore에는 .build/와 .swiftpm/이 없을 때만 추가돼요):');
      for (const file of await listFiles(stageDir)) log.info(`  ${file}`);
    }
    return;
  }

  // 태그를 푸시하기 전에 바이너리를 Draft Release로 먼저 올린다. 비공개 레포는 asset ID가 들어간 API 주소를 써야 해서다.
  log.step('GitHub Release(draft)에 XCFramework 올리기');
  await run('gh', [
    'release',
    'create',
    version,
    '--repo',
    repo,
    '--draft',
    '--title',
    `${config.name} ${version}`,
    '--notes',
    `Built with Nativepiece. \`.package(url: "https://github.com/${repo}", exact: "${version}")\``,
    ...assets.map((asset) => asset.file),
  ]);

  const isPrivate = (await run('gh', ['repo', 'view', repo, '--json', 'visibility', '--jq', '.visibility'], { inherit: false })).trim() !== 'PUBLIC';
  const assetIds = isPrivate ? await draftAssetIds(repo, version) : new Map<string, number>();
  const binary = (name: string) => {
    const asset = byName.get(name)!;
    // 비공개 레포의 일반 다운로드 주소는 토큰을 넣어도 404라서 API 주소를 쓴다. 공개 레포는 요청 제한이 없는 일반 주소를 쓴다.
    const url = isPrivate
      ? `https://api.github.com/repos/${repo}/releases/assets/${assetIds.get(assetName(name))}.zip`
      : `https://github.com/${repo}/releases/download/${version}/${assetName(name)}`;
    return `url: "${url}", checksum: "${asset.checksum}"`;
  };

  log.step('원격용 Package.swift 생성');
  if (target.mode === 'same') {
    await stagePackage(config, packageDir, target.gitRoot, target, manifest, binary);
    log.step(`${repo}에 ${version} 커밋과 푸시`);
    await pushSameRepository(target, version);
  } else {
    await stagePackage(config, packageDir, stageDir, target, manifest, binary);
    log.step(`${repo}에 ${version} 푸시`);
    await pushPackageRepository(repo, version, stageDir);
  }

  log.step('GitHub Release 공개');
  await run('gh', ['release', 'edit', version, '--repo', repo, '--draft=false'], { inherit: false });

  log.success(`배포했어요: https://github.com/${repo}/releases/tag/${version}`);
  log.info(`.package(url: "https://github.com/${repo}", exact: "${version}")`);
}
