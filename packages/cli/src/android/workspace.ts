// C++ autolinking 결과(libappmodules.so)를 만들기 위한 빈 앱 모듈이다. 결과물에는 .so만 가져간다.
function renderLinkageBuild(): string {
  return `// Generated by Nativepiece. Do not edit.
apply plugin: "com.android.application"
apply plugin: "org.jetbrains.kotlin.android"
apply plugin: "com.facebook.react"

react {
    autolinkLibrariesWithApp()
}

android {
    ndkVersion rootProject.ext.ndkVersion
    buildToolsVersion rootProject.ext.buildToolsVersion
    compileSdk rootProject.ext.compileSdkVersion
    namespace "io.nativepiece.linkage"

    defaultConfig {
        applicationId "io.nativepiece.linkage"
        minSdkVersion rootProject.ext.minSdkVersion
        targetSdkVersion rootProject.ext.targetSdkVersion
        versionCode 1
        versionName "1.0"
    }
}

kotlin {
    jvmToolchain(17)
}

dependencies {
    implementation("com.facebook.react:react-android")
    implementation("com.facebook.react:hermes-android")
}
`;
}

function renderSdkBuild(config: ResolvedConfig): string {
  const android = config.android!;
  return `// Generated by Nativepiece. Do not edit.
plugins {
    id "com.android.library"
    id "org.jetbrains.kotlin.android"
    id "maven-publish"
}

android {
    namespace ${groovyString(android.namespace)}
    compileSdk rootProject.ext.compileSdkVersion

    defaultConfig {
        minSdk rootProject.ext.minSdkVersion
        consumerProguardFiles "consumer-rules.pro"
    }

    sourceSets {
        main {
            java.srcDirs += ["src/generated/java"]
            assets.srcDirs += ["src/generated/assets"]
            res.srcDirs += ["src/generated/res"]
            jniLibs.srcDirs += ["src/generated/jniLibs"]
        }
    }

    compileOptions {
        sourceCompatibility JavaVersion.VERSION_17
        targetCompatibility JavaVersion.VERSION_17
    }

    publishing {
        singleVariant("release") {
            withSourcesJar()
        }
    }
}

kotlin {
    jvmToolchain(17)
}

dependencies {
    api("androidx.appcompat:appcompat:\${rootProject.ext.appcompatVersion}")
    api("com.facebook.react:react-android:\${rootProject.ext.reactNativeVersion}")
    api("com.facebook.hermes:hermes-android:\${rootProject.ext.hermesVersion}")

    // autolink된 네이티브 모듈을 모두 api 의존성으로 연결한다. 각 모듈은 같은 저장소에 AAR로 발행된다.
    rootProject.subprojects
        .findAll { it.path != project.path && it.path != ":${LINKAGE_PROJECT}" }
        .each { api(project(it.path)) }
}

afterEvaluate {
    publishing {
        publications {
            release(MavenPublication) {
                from components.release
                groupId = ${groovyString(android.group)}
                artifactId = ${groovyString(android.artifactId)}
                version = rootProject.ext.nativepieceVersion
                pom {
                    name = ${groovyString(`${config.name} Android`)}
                    description = "Built with Nativepiece"
                }
                pom.withXml { rootProject.ext.rewriteReactNativeDependencies(asNode()) }
            }
        }
        repositories {
            maven { name = "${REPOSITORY_NAME}"; url = rootProject.ext.repositoryDir }
        }
    }
}
`;
}

// autolinking 설정에서 ReactPackage 목록 클래스를 만든다. 호스트 SDK가 이 클래스로 런타임을 만든다.
function renderPackageList(autolinking: AutolinkingConfig): string {
  const packages = Object.entries(autolinking.dependencies ?? {})
    .map(([name, dependency]) => ({ name, android: dependency.platforms?.android }))
    .filter((dependency) => dependency.android?.packageImportPath && dependency.android?.packageInstance)
    .sort((left, right) => left.name.localeCompare(right.name));

  const imports = packages.map((dependency) => dependency.android!.packageImportPath!.trim()).join('\n');
  const instances = packages
    .map((dependency) => `,\n      // ${dependency.name}\n      ${dependency.android!.packageInstance!.trim()}`)
    .join('');

  return `// Generated by Nativepiece. Do not edit.
package io.nativepiece.host;

import android.app.Application;
import android.content.Context;
import android.content.res.Resources;

import com.facebook.react.ReactPackage;
import com.facebook.react.shell.MainReactPackage;

import java.util.ArrayList;
import java.util.Arrays;

${imports}

public final class NativepiecePackageList {
  private final Application application;

  public NativepiecePackageList(Application application) {
    this.application = application;
  }

  private Application getApplication() {
    return application;
  }

  private Resources getResources() {
    return application.getResources();
  }

  private Context getApplicationContext() {
    return application.getApplicationContext();
  }

  public ArrayList<ReactPackage> getPackages() {
    return new ArrayList<>(Arrays.<ReactPackage>asList(
      new MainReactPackage()${instances}
    ));
  }
}
`;
}

function androidSdkDir(): string {
  const candidates = [process.env.ANDROID_HOME, process.env.ANDROID_SDK_ROOT, path.join(os.homedir(), 'Library', 'Android', 'sdk')];
  const found = candidates.find((candidate) => candidate && existsSync(candidate));
  if (!found) throw new Error('Android SDK를 찾지 못했어요. ANDROID_HOME을 설정해 주세요.');
  return found;
}

export async function readAutolinkingConfig(project: RNProject, workspace: string): Promise<AutolinkingConfig> {
  const json = await run(process.execPath, [path.join(project.reactNativePath, 'cli.js'), 'config'], {
    cwd: project.root,
    inherit: false,
  });
  const config = JSON.parse(json) as AutolinkingConfig;
  // 앱 모듈의 C++ autolinking은 project.android 정보를 쓴다. android/ 폴더가 없는 모듈 프로젝트도 동작하도록 채운다.
  config.project = {
    ...(config.project ?? {}),
    android: {
      sourceDir: workspace,
      appName: LINKAGE_PROJECT,
      packageName: 'io.nativepiece.linkage',
      applicationId: 'io.nativepiece.linkage',
      mainActivity: '.MainActivity',
      dependencyConfiguration: 'implementation',
    },
  };
  return config;
}

export async function prepareAndroidWorkspace(config: ResolvedConfig, project: RNProject): Promise<AndroidWorkspace> {
  if (!config.android) {
    throw new Error('nativepiece.config.ts에 android 설정(group)이 필요해요.');
  }

  const dir = workspaceDir(project.root, 'android');
  const sdkDir = path.join(dir, SDK_PROJECT);
  const linkageDir = path.join(dir, LINKAGE_PROJECT);
  const repositoryDir = workspaceDir(project.root, 'output', 'android', 'maven');
  const versions = resolveVersions(config, project);

  await mkdir(path.join(linkageDir, 'src', 'main'), { recursive: true });
  await rm(path.join(sdkDir, 'src'), { recursive: true, force: true });
  await mkdir(path.join(sdkDir, 'src', 'generated', 'java', 'io', 'nativepiece', 'host'), { recursive: true });

  await cp(assetPath('android', 'gradle'), path.join(dir, 'gradle'), { recursive: true });
  await cp(assetPath('android', 'gradlew'), path.join(dir, 'gradlew'));
  await chmod(path.join(dir, 'gradlew'), 0o755);
  await cp(packagePath('assets', 'android-host', 'src', 'main'), path.join(sdkDir, 'src', 'main'), { recursive: true });

  const autolinkingConfig = await readAutolinkingConfig(project, dir);
  await writeFile(path.join(dir, 'autolinking-config.json'), JSON.stringify(autolinkingConfig, null, 2));
  await writeFile(path.join(dir, 'settings.gradle'), renderSettings(project));
  await writeFile(path.join(dir, 'build.gradle'), renderRootBuild(config, project, versions, repositoryDir));
  await writeFile(path.join(dir, 'gradle.properties'), renderGradleProperties(config));
  await writeFile(path.join(dir, 'local.properties'), `sdk.dir=${androidSdkDir()}\n`);
  await writeFile(path.join(linkageDir, 'build.gradle'), renderLinkageBuild());
  await writeFile(
    path.join(linkageDir, 'src', 'main', 'AndroidManifest.xml'),
    '<manifest xmlns:android="http://schemas.android.com/apk/res/android" />\n',
  );
  await writeFile(path.join(sdkDir, 'build.gradle'), renderSdkBuild(config));
  await writeFile(path.join(sdkDir, 'consumer-rules.pro'), '-keep class io.nativepiece.** { *; }\n');
  await writeFile(
    path.join(sdkDir, 'src', 'generated', 'java', 'io', 'nativepiece', 'host', 'NativepiecePackageList.java'),
    renderPackageList(autolinkingConfig),
  );

  return { dir, sdkDir, repositoryDir, versions, autolinkingConfig };
}
