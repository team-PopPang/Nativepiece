// 루트 빌드 스크립트. autolink된 네이티브 모듈을 각각 AAR로 발행하고, RN·Hermes 의존성을 정확한 버전으로 고정한다.
function renderRootBuild(config: ResolvedConfig, project: RNProject, versions: AndroidVersions, repositoryDir: string): string {
  return `// Generated by Nativepiece. Do not edit.
import org.gradle.api.publish.maven.MavenPublication
import org.gradle.api.publish.tasks.GenerateModuleMetadata
import groovy.json.JsonSlurper

buildscript {
    ext {
        buildToolsVersion = ${groovyString(versions.buildTools)}
        minSdkVersion = ${versions.minSdk}
        compileSdkVersion = ${versions.compileSdk}
        targetSdkVersion = ${versions.targetSdk}
        ndkVersion = ${groovyString(versions.ndkVersion)}
    }
    repositories {
        google()
        mavenCentral()
    }
    dependencies {
        classpath("com.android.tools.build:gradle")
        classpath("com.facebook.react:react-native-gradle-plugin")
        classpath("org.jetbrains.kotlin:kotlin-gradle-plugin")
    }
}

ext {
    nativepieceVersion = ${groovyString(config.version)}
    reactNativeVersion = ${groovyString(versions.reactNative)}
    hermesVersion = ${groovyString(versions.hermes)}
    appcompatVersion = ${groovyString(versions.appcompat)}
    prebuiltGroup = ${groovyString(`${config.android!.group}.nativepiece`)}
    repositoryDir = file(${groovyString(repositoryDir)})
}

def internalProjects = [":${LINKAGE_PROJECT}", ":${SDK_PROJECT}"]
def jsonSlurper = new JsonSlurper()

allprojects {
    configurations.configureEach { configuration ->
        configuration.resolutionStrategy.dependencySubstitution {
            substitute module("com.facebook.react:react-native") using module("com.facebook.react:react-android:\${rootProject.ext.reactNativeVersion}")
            substitute module("com.facebook.react:hermes-engine") using module("com.facebook.hermes:hermes-android:\${rootProject.ext.hermesVersion}")
            substitute module("com.facebook.react:hermes-android") using module("com.facebook.hermes:hermes-android:\${rootProject.ext.hermesVersion}")
        }
    }
}

subprojects { subproject ->
    // 라이브러리의 codegen이 모듈 프로젝트의 node_modules를 찾도록 경로를 명시한다.
    subproject.pluginManager.withPlugin("com.facebook.react") {
        subproject.react {
            root = file(${groovyString(project.root)})
            reactNativeDir = file(${groovyString(project.reactNativePath)})
            codegenDir = file(${groovyString(codegenPath(project))})
            cliFile = file(${groovyString(path.join(project.reactNativePath, 'cli.js'))})
        }
    }

    if (subproject.path in internalProjects) {
        return
    }

    def packageJsonFile = file("\${subproject.projectDir}/../package.json")
    def packageVersion = packageJsonFile.exists() ? jsonSlurper.parse(packageJsonFile).version.toString() : rootProject.ext.nativepieceVersion
    subproject.group = rootProject.ext.prebuiltGroup
    subproject.version = packageVersion

    subproject.pluginManager.withPlugin("com.android.library") {
        subproject.apply plugin: "maven-publish"

        subproject.android {
            compileOptions {
                sourceCompatibility JavaVersion.VERSION_17
                targetCompatibility JavaVersion.VERSION_17
            }
            publishing {
                singleVariant("release")
            }
        }

        // 네이티브 모듈의 원본 metadata에는 react-native:+ 같은 값이 남을 수 있어 POM만 발행한다.
        subproject.tasks.withType(GenerateModuleMetadata).configureEach { enabled = false }

        subproject.afterEvaluate {
            subproject.publishing {
                publications {
                    release(MavenPublication) {
                        from subproject.components.release
                        groupId = rootProject.ext.prebuiltGroup
                        artifactId = subproject.name
                        version = subproject.version.toString()
                        pom.withXml { rewriteReactNativeDependencies(asNode()) }
                    }
                }
                repositories {
                    maven { name = "${REPOSITORY_NAME}"; url = rootProject.ext.repositoryDir }
                }
            }
        }
    }

    subproject.pluginManager.withPlugin("org.jetbrains.kotlin.android") {
        subproject.kotlin.jvmToolchain(17)
    }
}

// POM의 RN·Hermes 의존성을 Maven Central에 실제로 있는 좌표와 버전으로 바꾼다.
def rewriteReactNativeDependencies(node) {
    (node.dependencies?.dependency ?: []).each { dependency ->
        def group = dependency.groupId[0]?.text()
        def artifact = dependency.artifactId[0]?.text()
        def versionNode = dependency.version[0]
        if (group == "com.facebook.react" && artifact in ["react-native", "react-android"]) {
            dependency.artifactId[0].setValue("react-android")
            if (versionNode) versionNode.setValue(rootProject.ext.reactNativeVersion)
            else dependency.appendNode("version", rootProject.ext.reactNativeVersion)
        }
        if (artifact in ["hermes-engine", "hermes-android"]) {
            dependency.groupId[0].setValue("com.facebook.hermes")
            dependency.artifactId[0].setValue("hermes-android")
            if (versionNode) versionNode.setValue(rootProject.ext.hermesVersion)
            else dependency.appendNode("version", rootProject.ext.hermesVersion)
        }
    }
}
ext.rewriteReactNativeDependencies = this.&rewriteReactNativeDependencies

// rootproject 플러그인은 :app을 먼저 평가하므로, 위의 subprojects 설정이 등록된 뒤에 적용한다.
apply plugin: "com.facebook.react.rootproject"

gradle.projectsEvaluated {
    tasks.register("publishNativepiece") { task ->
        task.dependsOn(subprojects.findAll { it.path != ":${LINKAGE_PROJECT}" }.collectMany { it.tasks.matching { t -> t.name == "publishAllPublicationsTo${REPOSITORY_NAME[0].toUpperCase()}${REPOSITORY_NAME.slice(1)}Repository" }.toList() })
    }
}
`;
}

